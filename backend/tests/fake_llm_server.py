"""Fake OpenAI-compatible server to exercise the real LLM code path offline
(prompt rendering, JSON mode, validation failure -> repair retry, chunk merge).
First response per conversation is deliberately INVALID (bad task_id, missing key, extra key);
the repair turn gets a valid payload generated by the mock parser from the chunk text."""
import json
import re
import sys
from pathlib import Path
from fastapi import FastAPI, Request
import uvicorn

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from app.mock_parser import mock_parse  # noqa: E402

app = FastAPI()
LOG = []


@app.post("/v1/chat/completions")
async def chat(req: Request):
    body = await req.json()
    msgs = body["messages"]
    first_user = next(m["content"] for m in msgs if m["role"] == "user")
    if first_user.startswith("Classify which numbered sentences"):        # safety span classifier
        sents = re.findall(r"^(\d+)\. (.*)$", first_user, re.M)
        crit = [{"i": int(i), "category": "llm"} for i, t in sents
                if re.search(r"\b(must|never|do not|warning|caution|immediately|lock|PPE|hazard)\b", t, re.I)]
        LOG.append({"classifier": True, "sentences": len(sents), "critical": len(crit)}); print("FAKE-LLM", LOG[-1], flush=True)
        return _reply(body, json.dumps({"critical": crit}))
    doc = re.search(r"<<<DOCUMENT_START>>>\n(.*)\n<<<DOCUMENT_END>>>", first_user, re.S).group(1)
    doc = re.sub(r"^\[\.\.\.continued from previous section\.\.\.\]\n.*?\n\[\.\.\.\]\n", "", doc, flags=re.S)
    is_repair = msgs[-1]["role"] == "user" and "previous response was invalid" in msgs[-1]["content"]
    data = mock_parse(doc)
    if not is_repair:
        bad = dict(data)
        bad.pop("document_summary")
        bad["confidence"] = 0.9
        bad["tasks"] = [dict(t, task_id=str(i)) for i, t in enumerate(data["tasks"], 1)]
        content = "```json\n" + json.dumps(bad) + "\n```"
    else:
        content = json.dumps(data)
    LOG.append({"repair": is_repair, "system_prompt_chars": len(msgs[0]["content"]),
                "response_format": body.get("response_format"), "model": body.get("model"), "temperature": body.get("temperature")})
    print("FAKE-LLM", LOG[-1], flush=True)
    return _reply(body, content)


def _reply(body, content):
    return {"id": "x", "object": "chat.completion", "created": 0, "model": body.get("model"),
            "choices": [{"index": 0, "finish_reason": "stop", "message": {"role": "assistant", "content": content}}],
            "usage": {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}}


@app.post("/v1/embeddings")
async def embeddings(req: Request):
    """Deterministic hashed bag-of-words vectors (stand-in for a real embedding model)."""
    body = await req.json()
    inputs = body["input"] if isinstance(body["input"], list) else [body["input"]]
    out = []
    for i, text in enumerate(inputs):
        v = [0.0] * 256
        for w in re.findall(r"[a-z0-9]+", text.lower()):
            v[hash(w) % 256] += 1.0
        out.append({"object": "embedding", "index": i, "embedding": v})
    LOG.append({"embeddings": len(inputs)}); print("FAKE-LLM", LOG[-1], flush=True)
    return {"object": "list", "data": out, "model": body.get("model"), "usage": {"prompt_tokens": 0, "total_tokens": 0}}


if __name__ == "__main__":
    uvicorn.run(app, host="127.0.0.1", port=int(sys.argv[1]) if len(sys.argv) > 1 else 8099)

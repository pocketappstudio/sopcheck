#!/usr/bin/env python3
"""Generate src/prompts.js from ../prompts/system_prompt.md (prompt sop-extract/1.2.0) so the Worker and backend share one source of truth."""
import re, json, pathlib
root = pathlib.Path(__file__).resolve().parents[2]
md = (root / "prompts" / "system_prompt.md").read_text(encoding="utf-8")
def section(name):
    m = re.search(rf"<!-- {name}_START -->\n(.*?)\n<!-- {name}_END -->", md, re.S)
    assert m, name
    return m.group(1).strip()
out = {"system": section("SYSTEM_PROMPT"), "user": section("USER_PROMPT"), "repair": section("REPAIR_PROMPT")}
js = "// GENERATED by scripts/gen_prompts.py from prompts/system_prompt.md - do not edit.\nexport const PROMPT_VERSION = \"sop-extract/1.2.0\";\nexport const PROMPTS = " + json.dumps(out, indent=1, ensure_ascii=False) + ";\n"
(root / "worker" / "src" / "prompts.js").write_text(js, encoding="utf-8")
print("wrote prompts.js", {k: len(v) for k, v in out.items()})
